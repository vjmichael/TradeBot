'use strict';
const assert=require('node:assert/strict');
const {view,ServiceStrip,REQUIRED}=require('./service_status_strip.cjs');
let checks=0;
const check=(actual,expected)=>{assert.equal(actual,expected);checks++};
const healthy=()=>({browserToServer:'reachable',internet:'online',receivedAtMs:100,services:Object.fromEntries(REQUIRED.map(k=>[k,'ready']))});
check(view(healthy(),100).services,'Services available');
check(view(healthy(),100).network,'Online');
check(view(healthy(),60100).services,'Checking services');
check(view({...healthy(),browserToServer:'unreachable'},100).network,'Server unreachable');
check(view({...healthy(),internet:'no_network_route'},100).network,'No internet connection');
check(view({...healthy(),internet:'dns_problem'},100).network,'DNS problem');
check(view({...healthy(),internet:'tls_problem'},100).network,'Secure connection problem');
check(view({...healthy(),internet:'unknown'},100).services,'Checking services');
check(view({...healthy(),services:{dashboard:'ready'}},100).services,'Checking services');
check(view({...healthy(),services:{...healthy().services,vault:'failed'}},100).services,'Services need attention');
check(view({...healthy(),services:{...healthy().services,risk_gate:'unknown'}},100).services,'Checking services');
check(view({...healthy(),receivedAtMs:101},100).services,'Checking services');
check(view(null,100).services,'Checking services');
check(view(healthy(),NaN).services,'Checking services');
let pressed=0;
const React={createElement:(type,props,...children)=>({type,props:props||{},children})};
const el=ServiceStrip({React,snapshot:healthy(),nowMs:100,onDetails:()=>pressed++});
check(el.type,'footer');check(el.props.role,'status');
const summary=el.children[0];check(summary.props.className,'maj-service-summary');
check(summary.children[1].children[0],'Online');
check(summary.children[2].children[0],'Services available');
const svg=summary.children[0];check(svg.type,'svg');check(svg.props['aria-hidden'],'true');
const btn=el.children[1];check(btn.type,'button');btn.props.onClick();check(pressed,1);
const failed=ServiceStrip({React,snapshot:{...healthy(),internet:'internet_unreachable'},nowMs:100});
check(failed.children[0].children[2].children[0]!=='Services available',true);
console.log('PASS',checks,'local status strip UI assertions');